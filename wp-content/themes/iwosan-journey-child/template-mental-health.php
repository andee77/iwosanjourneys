	<ul>
		<li><strong>Sleep Disruption</strong> — an inability to fall asleep, or waking up at 3:00 AM with a racing heart and unable to settle back down.</li>
		<li><strong>Digestive Distress</strong> — chronic stomach pain, acid reflux, or irritable bowel symptoms triggered by high cortisol levels.</li>
		<li><strong>Systemic Inflammation</strong> — unexplained joint aches, muscle tension (especially in the jaw and neck), and a weakened immune system.</li>
		<li><strong>Cognitive Blunting</strong> — severe brain fog, memory lapses, and the inability to focus on simple tasks.</li>
	</ul>

	<p style="clear: both;"><strong>The Action Step:</strong> Healing requires moving your nervous system from "survival mode" back to "repair mode." This involves setting ruthless boundaries, auditing your energy, and seeking collaborative psychiatric or therapeutic care when your biology needs a reset.</p>

	<h2>The everyday basics</h2>
	<p>Repair mode starts small. A few of the basics that move the needle most:</p>

	<ul>
		<li><strong>Move daily</strong> — even 30 minutes of walking, broken up however it fits, lifts mood and lowers stress.</li>
		<li><strong>Eat, hydrate, and watch the caffeine/alcohol</strong> — both can quietly worsen mood and sleep.</li>
		<li><strong>Protect sleep</strong> — a consistent schedule, and less blue light before bed.</li>
		<li><strong>Build in real rest</strong> — meditation, breathing work, music, time outside — whatever actually relaxes you, on a schedule.</li>
		<li><strong>Guard your energy</strong> — decide what matters today, let the rest wait, and get comfortable saying no.</li>
		<li><strong>Stay connected</strong> — the people in your corner are part of the treatment plan, not a nice-to-have.</li>
	</ul>

