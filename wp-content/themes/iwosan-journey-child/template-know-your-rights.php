	<p>You don't have to know medical jargon to be taken seriously in a doctor's office. You just have to know what you're actually entitled to — and most people never get told.</p>

	<h2>What you're entitled to, every visit</h2>

	<p><strong>The full picture, in plain language.</strong><br>
	You have the right to a clear explanation of your diagnosis, your options, and the risks and benefits of each — not a rushed summary. If something doesn't make sense, you're allowed to ask again until it does.</p>

	<p><strong>Your own records, on request.</strong><br>
	Your medical history belongs to you. You can request copies of your chart, your test results, and your visit notes — and a provider can't refuse just because they'd rather you not see how something was documented.</p>

	<p><strong>A second opinion, no permission needed.</strong><br>
	You don't have to justify wanting one. Seeking a second opinion isn't an insult to your provider — it's a normal, expected part of getting real answers, especially for anything serious or ongoing.</p>

	<p><strong>The right to say no.</strong><br>
	You can decline a test, a medication, or a procedure — even one your provider recommends — as long as you understand what that choice means. Consent has to be informed, and it has to be yours.</p>

	<p><strong>Care that isn't shaped by bias.</strong><br>
	You're entitled to the same quality of care regardless of your race, gender, age, weight, income, or where you're from. If you feel like you're getting a different standard of care than someone else would, that's worth naming — not something to just accept.</p>

	<p><strong>A real complaint process.</strong><br>
	If a provider dismisses you, mistreats you, or gives you substandard care, you can file a complaint — with the practice's patient advocate, the hospital's patient relations department, or your state's medical board. This isn't an extreme step. It's a documented part of how the system is supposed to hold itself accountable.</p>

	<h2>When something feels off</h2>

	<p>If you walk away from an appointment feeling unheard, here's what actually helps:</p>

	<ul>
		<li><strong>Write it down while it's fresh</strong> — the date, what was said, and what was (or wasn't) offered.</li>
		<li><strong>Ask for it in your chart.</strong> "Please document that I raised this concern and what your response was" is a completely reasonable request, and it creates a real record.</li>
		<li><strong>You can change providers.</strong> Fit matters. If a provider consistently dismisses you, finding someone else isn't giving up — it's advocating for yourself.</li>
	</ul>

