	<p>Your child can't always tell you what's wrong. They definitely can't tell a pediatrician who's meeting them for the first time. That job falls to you — and it's a real, legitimate form of advocacy, not just being an anxious parent.</p>

	<h2>Why this is different</h2>
	<p>A lot of advocacy is about speaking up for yourself. This is about speaking up for someone who doesn't yet have the words — or the standing in the room — to do it themselves. That comes with its own challenges:</p>
	<ul>
		<li>Symptoms in kids often show up as behavior changes, not clear complaints.</li>
		<li>"Wait and see" is sometimes the right call — but it should come with a specific timeline, not an open-ended shrug.</li>
		<li>You're often the only person tracking the full picture across pediatricians, specialists, and school.</li>
	</ul>

	<h2>What you're entitled to as a parent</h2>

	<p><strong>To be heard, not just heard out.</strong><br>
	You know your child's baseline better than anyone in the room. If something feels off, that observation is real data — not something to be talked out of.</p>

	<p><strong>A clear timeline, not an open-ended "let's watch it."</strong><br>
	You can ask directly: "What specifically should prompt me to call sooner than our next visit?" A vague answer isn't a real answer.</p>

	<p><strong>Documentation.</strong><br>
	If a concern is raised and the plan is to wait, you can ask for that to be noted in the chart — useful if you end up seeing a different provider, or if the issue resurfaces months later.</p>

	<p><strong>A second opinion, without guilt.</strong><br>
	Wanting another set of eyes on your child's care isn't distrust. It's due diligence, and any provider worth keeping will understand that.</p>

	<h2>Scripts that work</h2>

	<div class="ij-quote">"I'd like this documented as an ongoing concern, not a one-time note, and I'd like to understand what we're watching for and when I should call sooner."</div>

	<p style="margin-top: 20px;">If you feel rushed:</p>
	<div class="ij-quote">"Before we wrap up, I have two more things on my list I need addressed today."</div>

	<p style="margin-top: 20px;">If a concern gets waved off:</p>
	<div class="ij-quote">"Can we talk through why you're not concerned, so I understand the reasoning — not just the conclusion?"</div>

